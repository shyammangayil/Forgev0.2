"""
FORGE Configuration Management
==============================
All configuration is driven by environment variables with safe defaults.
Never store secrets in source code.
"""
from __future__ import annotations

import os
import json
from dataclasses import dataclass, field
from typing import Optional
from pathlib import Path

from dotenv import load_dotenv

# Load .env from the directory Forge is run from.
# override=False means real OS environment variables always take priority.
load_dotenv(override=False)


@dataclass
class ProviderConfig:
    name: str
    api_key_env: str
    base_url: str
    enabled: bool = True
    timeout_seconds: int = 120
    max_retries: int = 3

    @property
    def api_key(self) -> Optional[str]:
        return os.environ.get(self.api_key_env)

    @property
    def is_available(self) -> bool:
        return self.enabled and bool(self.api_key)


@dataclass
class RouterConfig:
    """Task-type to provider routing policy."""
    coding_provider:       str  = "anthropic"
    review_provider:       str  = "openai"
    large_context_provider:str  = "gemini"
    offline_provider:      str  = "ollama"
    reasoning_provider:    str  = ""        # "" = use large_context_provider; set to "litellm" by local stack
    vision_provider:       str  = ""        # "" = use coding_provider; set to "litellm" by local stack
    default_provider:      str  = "anthropic"
    fallback_chain:        list = field(default_factory=lambda: [
        "anthropic", "openai", "gemini", "ollama"
    ])
    # Per-provider model overrides — empty string means use provider default
    anthropic_model:  str = ""
    openai_model:     str = ""
    gemini_model:     str = ""
    ollama_model:     str = ""
    openrouter_model: str = ""
    litellm_model:    str = ""   # alias passed to llama-swap (e.g. qwen3)
    # Role → alias mapping (used when local stack is active)
    coding_model:    str = "qwen3"      # alias for coding tasks
    reasoning_model: str = "deepseek"   # alias for planning/analysis tasks
    vision_model:    str = "qwen3vl"    # alias for vision tasks


