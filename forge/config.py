@dataclass
class ModelProfile:
    """
    Maps a user-facing role (coding / reasoning / vision) to a GGUF
    model file and the llama-swap alias used to request it.

    Users never see filenames or aliases — they pick a role.
    Forge translates role → alias → llama-swap → llama.cpp → GGUF.
    """
    role:        str            # coding | reasoning | vision | custom
    alias:       str            # llama-swap alias (e.g. qwen3, deepseek)
    model_path:  str            # absolute path to .gguf file
    mmproj_path: str  = ""      # multimodal projection file (vision only)
    context_len: int  = 4096    # -c flag for llama-server
    gpu_layers:  int  = 99      # -ngl flag (99 = all layers on GPU)
    threads:     int  = 8       # -t flag for CPU threads
    description: str  = ""      # human-readable, shown in forge stack models


@dataclass
class LocalStackConfig:
    """
    Configuration for the Forge Thunderbird local LLM stack.

    Stack architecture:
        llama.cpp (llama-server) ← llama-swap ← LiteLLM ← Forge router

    All YAML config files are auto-generated by Forge from this config
    and the discovered GGUF files — users never edit YAML directly.
    """
    enabled:              bool        = False
    # Binary paths
    llama_cpp_binary:     str         = ""      # path to llama-server.exe / llama-server
    llama_swap_binary:    str         = ""      # path to llama-swap binary
    # Ports
    llama_server_port:    int         = 8081    # llama.cpp HTTP port (managed by llama-swap)
    llama_swap_port:      int         = 8080    # llama-swap aggregation port
    litellm_port:         int         = 4000    # LiteLLM OpenAI-compatible port
    # Model directories to scan (list of paths)
    models_dirs:          list        = field(default_factory=list)
    # Auto-generated config file locations
    llama_swap_config:    str         = "llama_swap_config.yaml"
    litellm_config:       str         = "litellm_config.yaml"
    # Model profiles (populated by ModelRegistry.scan() or from env)
    model_profiles:       dict        = field(default_factory=dict)  # role → ModelProfile
    # Behaviour
    auto_generate_configs:bool        = True    # write YAML on forge stack start
    gpu_layers:           int         = 99      # default -ngl for all models
    threads:              int         = 8       # default -t for all models


@dataclass
class TestIntelligenceConfig:
    """Configuration for the Test Intelligence Engine."""
