"""
FORGE Thunderbird — Config Generator
======================================
Auto-generates llama-swap and LiteLLM YAML configuration files
from ModelRegistry output. Users never edit these files manually.

llama-swap config
-----------------
Tells llama-swap which llama-server command to run for each model alias.
When Forge (via LiteLLM) requests model "deepseek", llama-swap kills the
current llama-server process and spawns the deepseek command — seamless
hot-swap with no user action required.

LiteLLM config
--------------
Maps each model alias to its llama-swap HTTP endpoint. LiteLLM exposes
all aliases on a single OpenAI-compatible port (4000) and routes each
request to llama-swap (8080) with the right model header.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Optional

from forge.telemetry.logger import get_logger

log = get_logger("local_stack.config_generator")


def generate_llama_swap_config(
    registry,           # ModelRegistry instance
    output_path: str,
    llama_cpp_binary: str,
    llama_server_port: int = 8081,
    llama_swap_port:   int = 8080,
) -> str:
    """
    Write a llama-swap YAML config file.

    llama-swap listens on llama_swap_port (8080) and forwards to
    llama-server on llama_server_port (8081). When the requested model
    alias changes it kills the old llama-server and spawns the new one.

    Returns the YAML content as a string (also written to output_path).
    """
    if not llama_cpp_binary:
        log.warning("No llama_cpp_binary configured — using 'llama-server' on PATH")
        binary = "llama-server"
    else:
        # Normalise path separators for the running OS
        binary = str(Path(llama_cpp_binary))

    models_section = ""
    for role, profile in registry.profiles.items():
        model_path = str(Path(profile.model_path))

        # Base command
        cmd_parts = [
            f'"{binary}"',
            f'-m "{model_path}"',
            f"--port {llama_server_port}",
            f"-ngl {profile.gpu_layers}",
            f"-t {profile.threads}",
            f"-c {profile.context_len}",
            "--host 127.0.0.1",
        ]

        # Vision model: add mmproj
        if profile.mmproj_path:
            mmproj = str(Path(profile.mmproj_path))
            cmd_parts.append(f'--mmproj "{mmproj}"')

        cmd = " ".join(cmd_parts)

        models_section += f"""
  {profile.alias}:
    cmd: {cmd}
    # Role: {role}  |  Size: {profile.size_gb:.1f}GB
"""

    yaml_content = f"""# FORGE Thunderbird — llama-swap configuration
# Auto-generated by forge. Do not edit manually — run 'forge stack config'
# to regenerate from your .env and model directory settings.
#
# llama-swap listens on port {llama_swap_port} and routes to
# llama-server on port {llama_server_port}.

host: 127.0.0.1
port: {llama_swap_port}

models:{models_section}
"""

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(yaml_content, encoding="utf-8")
    log.info("llama-swap config written", path=str(out))
    return yaml_content


def generate_litellm_config(
    registry,
    output_path:    str,
    llama_swap_port: int = 8080,
    litellm_port:    int = 4000,
    master_key:      Optional[str] = None,
) -> str:
    """
    Write a LiteLLM proxy config file.

    LiteLLM listens on litellm_port (4000) and forwards each request
    to llama-swap on llama_swap_port (8080) with the model alias intact.
    Cloud providers are added as additional entries if API keys are set.
    """
    model_list_section = ""
    for role, profile in registry.profiles.items():
        model_list_section += f"""
  - model_name: {profile.alias}
    litellm_params:
      model: openai/{profile.alias}
      api_base: http://127.0.0.1:{llama_swap_port}
      api_key: "none"
    # Role: {role}  |  {profile.description}
"""

    # Cloud fallbacks — only added when API keys are present in env
    import os
    cloud_section = ""
    cloud_models = [
        ("ANTHROPIC_API_KEY",  "claude-sonnet-4-6",           "anthropic/claude-sonnet-4-6",           ""),
        ("OPENAI_API_KEY",     "gpt-4o",                      "openai/gpt-4o",                         ""),
        ("GOOGLE_API_KEY",     "gemini-1.5-pro",              "gemini/gemini-1.5-pro",                 ""),
        ("OPENROUTER_API_KEY", "openrouter/auto",             "openrouter/auto",                       "https://openrouter.ai/api/v1"),
    ]
    for env_var, model_name, litellm_model, api_base in cloud_models:
        key = os.environ.get(env_var, "")
        if key:
            base_line = f'      api_base: "{api_base}"\n' if api_base else ""
            cloud_section += f"""
  - model_name: {model_name}
    litellm_params:
      model: {litellm_model}
      api_key: "{key}"
{base_line}"""

    key_line = f'\ngeneral_settings:\n  master_key: "{master_key}"\n' if master_key else ""

    yaml_content = f"""# FORGE Thunderbird — LiteLLM proxy configuration
# Auto-generated by forge. Do not edit manually — run 'forge stack config'
# to regenerate.
#
# LiteLLM listens on port {litellm_port} (OpenAI-compatible API).
# Local models route through llama-swap on port {llama_swap_port}.

model_list:{model_list_section}{cloud_section}
litellm_settings:
  drop_params: true          # ignore unsupported params silently
  request_timeout: 600       # 10 min timeout for long local inference
  num_retries: 1
{key_line}
"""

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(yaml_content, encoding="utf-8")
    log.info("LiteLLM config written", path=str(out))
    return yaml_content


def generate_all(
    registry,
    local_stack_cfg,   # LocalStackConfig
    output_dir: str = ".",
) -> dict:
    """
    Generate both config files. Returns dict with file paths.
    Called by `forge stack start` and `forge stack config`.
    """
    llama_swap_path = str(Path(output_dir) / local_stack_cfg.llama_swap_config)
    litellm_path    = str(Path(output_dir) / local_stack_cfg.litellm_config)

    import os
    master_key = os.environ.get("LITELLM_MASTER_KEY", "")

    generate_llama_swap_config(
        registry         = registry,
        output_path      = llama_swap_path,
        llama_cpp_binary = local_stack_cfg.llama_cpp_binary,
        llama_server_port= local_stack_cfg.llama_server_port,
        llama_swap_port  = local_stack_cfg.llama_swap_port,
    )

    generate_litellm_config(
        registry         = registry,
        output_path      = litellm_path,
        llama_swap_port  = local_stack_cfg.llama_swap_port,
        litellm_port     = local_stack_cfg.litellm_port,
        master_key       = master_key or None,
    )

    return {
        "llama_swap_config": llama_swap_path,
        "litellm_config":    litellm_path,
    }
